<section class="col-12" style="background-color: white">
  <div class="container site-section site-policy element-green-bg rounded" style="padding-bottom: 15px;">
    <h2>Plan de Prevención de Riesgos Laborales</h2>
    <p><em>Última actualización: 18 de Noviembre de 2025</em></p>

    <p>El presente Plan de Prevención de Riesgos Laborales (en adelante, el "Plan") establece las medidas mínimas de seguridad y salud que FarmXPress aplica en el marco de su actividad de renting de maquinaria agrícola, incluyendo las operaciones realizadas por el personal de la empresa y por terceros colaboradores o usuarios cuando proceda.</p>

    <h2>1. Objetivo</h2>
    <p>El objetivo del Plan es identificar, evaluar y controlar los riesgos laborales inherentes a la actividad de alquiler, transporte, entrega, recepción, mantenimiento y uso de maquinaria agrícola, asegurando la protección de la salud de trabajadores, clientes y terceros.</p>

    <h2>2. Ámbito de aplicación</h2>
    <p>Este Plan se aplica a todo el personal de FarmXPress, a los proveedores y a los clientes que utilicen la plataforma y los servicios de renting de maquinaria. Abarca actividades administrativas, logísticas, de almacenamiento, carga/descarga, transporte y mantenimiento técnico de equipos.</p>

    <h2>3. Responsabilidades</h2>
    <ul>
      <li><strong>Dirección:</strong> Aprobar el Plan, asignar recursos y velar por su cumplimiento.</li>
      <li><strong>Responsable de Prevención:</strong> Coordinar las actuaciones preventivas, realizar evaluaciones de riesgo y revisar el Plan periódicamente.</li>
      <li><strong>Supervisores logísticos y técnicos:</strong> Aplicar procedimientos de trabajo seguro y comprobar el estado de la maquinaria antes y después del alquiler.</li>
      <li><strong>Trabajadores y terceros:</strong> Cumplir las instrucciones y acudir a la formación y la información provista por la empresa.</li>
    </ul>

    <h2>4. Identificación y evaluación de riesgos</h2>
    <p>Se deberán identificar y evaluar los riesgos asociados a cada fase del servicio, entre ellos:</p>
    <ul>
      <li>Manipulación manual de cargas y esfuerzo físico al cargar/descargar maquinaria.</li>
      <li>Riesgos por vuelco, atrapamiento o contacto con partes móviles durante el uso de la maquinaria.</li>
      <li>Riesgos derivados del transporte de equipos (seguridad en la sujeción y estabilidad).</li>
      <li>Exposición a ruido y vibraciones, productos químicos (combustibles, lubricantes) y condiciones climáticas.</li>
      <li>Riesgos ergonómicos y accidentes en tareas de mantenimiento.</li>
    </ul>

    <h2>5. Medidas preventivas y de protección</h2>
    <ul>
      <li><strong>Mantenimiento preventivo:</strong> Programar y documentar revisiones periódicas de la maquinaria antes y después de cada alquiler.</li>
      <li><strong>Listas de comprobación (checklists):</strong> Implementar checklists para entrega/recepción que incluyan puntos críticos (frenos, luces, hidráulica, sujeción).</li>
      <li><strong>Formación y competencia:</strong> Exigir y ofrecer formación específica para manejo seguro de cada tipo de máquina; registrar la formación de clientes y operarios.</li>
      <li><strong>Equipos de protección individual (EPI):</strong> Suministrar y exigir el uso de EPIs adecuados (casco, guantes, calzado de seguridad, protección auditiva, gafas, etc.).</li>
      <li><strong>Procedimientos de carga y transporte:</strong> Establecer instrucciones claras para la sujeción, señalización y transporte seguro de maquinaria.</li>
      <li><strong>Señalización y delimitación:</strong> Señalizar las zonas de carga/descarga y mantenimiento, y controlar el acceso de personas no autorizadas.</li>
      <li><strong>Gestión de sustancias peligrosas:</strong> Almacenar y manipular combustibles y lubricantes conforme a la normativa, con hojas de datos de seguridad disponibles.</li>
      <li><strong>Emergencias:</strong> Contar con procedimientos de actuación ante accidentes, incendios y vertidos; disponer de botiquín y medios de extinción adecuados.</li>
    </ul>

    <h2>6. Formación, información y comunicación</h2>
    <p>FarmXPress facilitará a su personal y, cuando proceda, a los clientes, información comprensible sobre los riesgos, instrucciones de uso seguro y medidas de prevención. Se realizarán acciones formativas periódicas y registros de asistencia y contenidos.</p>

    <h2>7. Vigilancia de la salud</h2>
    <p>Cuando las actividades lo requieran, la empresa garantizará la vigilancia de la salud de los trabajadores mediante reconocimientos periódicos y seguimiento conforme a la normativa aplicable.</p>

    <h2>8. Gestión de incidentes y notificación</h2>
    <p>Se establece la obligación de notificar cualquier accidente o incidente (con o sin baja) a la dirección y al responsable de prevención. Se investigarán las causas y se definirán medidas correctoras para evitar su repetición.</p>

    <h2>9. Contratistas y usuarios externos</h2>
    <p>Los contratistas y clientes que realicen tareas en nombre de FarmXPress o utilicen la maquinaria serán informados de los riesgos y las medidas aplicables. En los contratos o condiciones de alquiler se incluirán cláusulas sobre responsabilidad y obligaciones en materia de seguridad.</p>

    <h2>10. Revisión y mejora continua</h2>
    <p>El Plan será revisado al menos una vez al año o cuando se produzcan cambios significativos en la actividad, nueva normativa, incidentes relevantes o incorporación de nueva maquinaria. Las auditorías internas verificarán su cumplimiento.</p>

    <h2>11. Contacto</h2>
    <p>Para dudas, sugerencias o la notificación de incidencias relacionadas con seguridad y salud, contacte con:</p>
    <ul>
